/**
 * Filter verified leads matching query and location.
 */
export function getVerifiedBusinesses(
  query: string,
  location: string,
  count: number = 5,
  offset: number = 0
): RealVerifiedBusiness[] {
  const normQuery = (query || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();
  const normLoc = (location || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();

  // Score matches based on city, state, query terms
  const scored = REAL_VERIFIED_DATABASE.map(b => {
    const bCity = b.city.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    const bState = b.state.toLowerCase();
    const bName = b.name.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    const bCompany = b.company.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    const bCat = b.category.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');

    let score = 0;

    // Location matching
    if (normLoc.includes(bCity) || bCity.includes(normLoc)) {
      score += 100;
    } else if (normLoc.includes(bState) || normLoc.includes(b.ddd)) {
      score += 30;
    }

    // Query term matching
    const isGasQuery = normQuery.includes('posto') || normQuery.includes('combustivel') || normQuery.includes('gasolina') || normQuery.includes('diesel') || normQuery.includes('lubrificante') || normQuery.includes('abastecimento');
    const isAgroQuery = normQuery.includes('cana') || normQuery.includes('usina') || normQuery.includes('rural') || normQuery.includes('fazenda') || normQuery.includes('agro') || normQuery.includes('produtor');

    if (isGasQuery && (bCat.includes('posto') || bCat.includes('combustivel'))) {
      score += 50;
    }
    if (isAgroQuery && (bCat.includes('usina') || bCat.includes('cooperativa') || bCat.includes('agro'))) {
      score += 50;
    }
    if (bName.includes(normQuery) || bCompany.includes(normQuery) || normQuery.includes(bName)) {
      score += 40;
    }

    return { business: b, score };
  });

  scored.sort((a, b) => b.score - a.score);

  // If we have strong matches (score >= 40), return distinct items
  const valid = scored.filter(s => s.score >= 40).map(s => s.business);
  if (valid.length > 0) {
    if (valid.length <= count && offset === 0) {
      return [...valid];
    }
    const result: RealVerifiedBusiness[] = [];
    const usedIds = new Set<string>();
    const totalToTake = Math.min(count, valid.length);
    for (let i = 0; i < valid.length && result.length < totalToTake; i++) {
      const idx = (offset + i) % valid.length;
      const b = valid[idx];
      if (!usedIds.has(b.id)) {
        usedIds.add(b.id);
        result.push(b);
      }
    }
    return result;
  }

  // Fallback to top scored businesses
  const fallbackList = scored.map(s => s.business);
  const result: RealVerifiedBusiness[] = [];
  const usedIds = new Set<string>();
  const totalToTake = Math.min(count, fallbackList.length);
  for (let i = 0; i < fallbackList.length && result.length < totalToTake; i++) {
    const idx = (offset + i) % fallbackList.length;
    const b = fallbackList[idx];
    if (!usedIds.has(b.id)) {
      usedIds.add(b.id);
      result.push(b);
    }
  }
  return result;
}
